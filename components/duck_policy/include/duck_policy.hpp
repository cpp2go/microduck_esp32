// INT8-weight inference for Microduck policies on ESP32 (P4 target in microduck_esp32).
//
// The models are the exported actor MLPs: normalize -> [Gemm -> Elu] x N ->
// Gemm. Weights are per-channel symmetric INT8 (the 773 KiB -> 193 KiB shrink
// per model is the whole point: a pass is PSRAM-bandwidth-bound); activations,
// scales, biases and the ELU stay FP32, so quantization error is limited to
// weight rounding.
//
// Multiple policies are baked into one firmware and hot-swappable at runtime:
// `kModels` is the registry (generated by tools/bake_policies.py), every entry
// carries its own FP32 golden vectors for the on-device accuracy gate, and
// `SetModel` swaps the active policy between control ticks — no hidden state,
// so switching is safe anywhere outside a Run() call on the same workspace.
#pragma once

#include <cstddef>
#include <cstdint>

namespace duck {

// Largest hidden width across the official policy set; bounds static sizing
// only — the workspace is computed from the active model's real widths.
constexpr int kMaxHidden = 512;

struct Layer {
    int in, out;
    const int8_t *wq;      // row-major [out][in], matches ONNX Gemm transB=1
    const float *wscale;   // [out] per-output-channel dequant scale
    const float *b;        // [out] FP32 bias
    bool elu;              // apply ELU(alpha=1) after this layer
};

struct Model {
    const char *name;
    int obs_len, act_len;
    int n_layers;
    const float *norm_mean; // [obs_len]
    const float *norm_std;  // [obs_len]
    Layer layers[8];

    // FP32 ONNX-Runtime reference I/O for the accuracy gate. First half of the
    // vectors is off-distribution (uniform random), second half is around
    // norm_mean (a plausible standing pose) — see README "quantization".
    int golden_count;
    const float *golden_obs; // [golden_count][obs_len]
    const float *golden_act; // [golden_count][act_len]
};

// The generated policy registry (duck_models.cpp), sorted with the default
// (alpha_walking) first.
extern const Model *const kModels[];
extern const int kModelCount;

/// Registry entry i, or nullptr when out of range.
const Model *ModelAt(int i);

/// Find a model by registry name; nullptr if absent.
const Model *FindModel(const char *name);

/// Active policy for Run(). Defaults to kModels[0]. The swap is a single
/// aligned pointer store — safe from another task while a control tick is not
/// in flight.
void SetModel(const Model *m);
const Model *CurrentModel();

// Workspace size in floats for the active model: two hidden buffers, ping-pong.
size_t WorkspaceFloats();

// One forward pass on the ACTIVE model. `obs` is the RAW (unnormalized)
// observation — the baked-in normalizer is applied here, exactly as the
// exported ONNX graph does. `ws` must hold WorkspaceFloats() floats, 4-byte
// aligned, and belong to the calling task (no internal locking).
void Run(const float *obs, float *actions, float *ws);

} // namespace duck
